const DICTS: Record<Lang, Dict> = {
  "zh-CN": zh,
  "en-US": en,
  "ja-JP": ja,
  "ko-KR": ko,
};

export function dict(lang: string): Dict {
  return DICTS[lang as Lang] ?? zh;
}

/** Localize a verify_api_key error code from Rust. */
export function verifyError(t: Dict, raw: string): string {
  const msg = raw.replace(/^Error:?\s*/i, "");
  if (msg === "empty_key") return t.verifyEmptyKey;
  if (msg === "bad_url") return t.verifyBadUrl;
  if (msg === "unauthorized") return t.verifyUnauthorized;
  if (msg === "not_found") return t.verifyNotFound;
  if (msg.startsWith("status:")) return t.verifyStatus(msg.slice(7));
  if (msg.startsWith("network:")) return t.verifyNetwork(msg.slice(8));
  return msg;
}
